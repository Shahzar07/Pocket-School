export function flowById(id: string): FlowSpec | undefined {
  return FLOWS.find((item) => item.id === id);
}

export function flowForPath(pathname: string): FlowSpec | null {
  const exact = FLOWS.find((item) => item.routes.includes(pathname));
  if (exact) return exact;
  const prefixed = FLOWS.filter((item) => item.prefixes.some((prefix) => pathname.startsWith(prefix)));
  prefixed.sort((a, b) => {
    const length = (specItem: FlowSpec) => Math.max(...specItem.prefixes.map((prefix) => prefix.length));
    return length(b) - length(a);
  });
  return prefixed[0] ?? null;
}

export function flowNote(route: string, fallback: string): string {
  return flowForPath(route)?.note ?? fallback;
}
