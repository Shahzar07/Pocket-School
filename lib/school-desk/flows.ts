export type FlowId =
  | 'home' | 'studio' | 'course' | 'marketplace' | 'read' | 'wallet' | 'referral' | 'message'
  | 'analytics' | 'insight' | 'progress' | 'reference'
  | 'exam' | 'live' | 'integrity' | 'case' | 'reportPack' | 'behaviour' | 'merit'
  | 'community' | 'network' | 'tutor' | 'sitting' | 'store'
  | 'announcement' | 'calendar' | 'resource' | 'card' | 'profile'
  | 'insights' | 'approval' | 'join' | 'alumni' | 'career' | 'verify' | 'publishing'
  | 'spark' | 'billing' | 'usage' | 'onboarding' | 'template' | 'activity'
  | 'risk' | 'certificate' | 'group' | 'destination' | 'price' | 'automation' | 'lead';

export interface FlowSpec {
  id: FlowId;
  routes: string[];
  prefixes: string[];
  mode: 'replace' | 'prepend';
  title: string;
  lede: string;
  who: string;
  data: string;
  created: string;
  syncs: string;
  note: string;
  empty: string;
  statuses: string[];
  needsStudent: boolean;
  summary: boolean;
  wall: boolean;
  titleLabel: string;
  detailLabel: string;
}

