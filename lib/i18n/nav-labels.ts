interface Phrase {
  tasks: string;
  myProgress: string;
  childDetail: string;
  network: string;
  memberCard: string;
  queues: string;
  actionCentre: string;
  automation: string;
  platformTools: string;
  pulse: string;
  safetyDesk: string;
  emergencyAlerts: string;
  pathways: string;
  examPacks: string;
  calendarTerms: string;
  copyrightSignatures: string;
  partnerPerks: string;
  schoolLeads: string;
  badges: string;
  storeImport: string;
  studyPlanner: string;
  classRisk: string;
  goalAdherence: string;
  atRisk: string;
  studio: string;
  groups: string;
  curriculum: string;
}

function pack(phrase: Phrase, schoolTimetable = PRODUCT.schoolTimetable): ExtraNav {
  return {
    ...PRODUCT,
    schoolTimetable,
    tasks: phrase.tasks,
    myProgress: phrase.myProgress,
    childDetail: phrase.childDetail,
    network: phrase.network,
    memberCard: phrase.memberCard,
    queues: phrase.queues,
    actionCentre: phrase.actionCentre,
    automation: phrase.automation,
    platformTools: phrase.platformTools,
    pulse: phrase.pulse,
    safetyDesk: phrase.safetyDesk,
    emergencyAlerts: phrase.emergencyAlerts,
    pathways: phrase.pathways,
    examPacks: phrase.examPacks,
    calendarTerms: phrase.calendarTerms,
    copyrightSignatures: phrase.copyrightSignatures,
    partnerPerks: phrase.partnerPerks,
    schoolLeads: phrase.schoolLeads,
    badges: phrase.badges,
    storeImport: phrase.storeImport,
    studyPlanner: phrase.studyPlanner,
    classRisk: phrase.classRisk,
    goalAdherence: phrase.goalAdherence,
    atRisk: phrase.atRisk,
    section: {
      studio: phrase.studio,
      groups: phrase.groups,
      curriculum: phrase.curriculum,
    },
  };
}

