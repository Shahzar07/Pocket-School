const byPath = new Map(DASHBOARD_PAGES.map((page) => [page.path, page]));

/** Longest matching pattern, so /dashboard/student/goals beats /dashboard/student. */
export function pageForPath(pathname: string): DashboardPage | null {
  const path = pathname.split('?')[0]?.replace(/\/$/, '') || '/';
  if (byPath.has(path)) return byPath.get(path) ?? null;
  let best: DashboardPage | null = null;
  for (const page of DASHBOARD_PAGES) {
    if (!page.path.includes('[')) continue;
    const re = new RegExp(`^${page.path.replace(/\[[^\]]+\]/g, '[^/]+')}$`);
    if (re.test(path) && (!best || page.path.length > best.path.length)) best = page;
  }
  return best;
}

